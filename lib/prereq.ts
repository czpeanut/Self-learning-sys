export type UnitRef = { book: string; unit: string }
const parse = (k: string): UnitRef => { const [book, unit] = k.split(':'); return { book, unit } }

/** 某單元的前置單元：直接前置＋再往前一層，最多 limit 個（近的在前） */
export function prereqUnits(book: string, unit: string, limit = 6): UnitRef[] {
  const direct = PREREQ[`${book}:${unit}`] ?? []
  const out: string[] = []
  for (const k of direct) if (!out.includes(k)) out.push(k)
  for (const k of direct) for (const k2 of PREREQ[k] ?? []) if (!out.includes(k2) && k2 !== `${book}:${unit}`) out.push(k2)
  return out.slice(0, limit).map(parse)
}
