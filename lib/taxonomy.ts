// 取得某科目的「大單元（大章節）」清單
export function getChapters(subject: string): string[] {
  return Object.keys(TAXONOMY[subject] ?? {})
}

// 取得某科目（或某大單元）的「知識點」清單
export function getKnowledgePoints(subject: string, chapter?: string): string[] {
  const units = TAXONOMY[subject]
  if (!units) return []
  if (chapter != null && chapter !== '') return units[chapter] ?? []
  return Object.values(units).flat()
}

// 由知識點反查其所屬的大單元；找不到回傳空字串
export function getUnitOf(subject: string, knowledgePoint: string): string {
  const units = TAXONOMY[subject]
  if (!units || !knowledgePoint) return ''
  for (const [unit, kps] of Object.entries(units)) {
    if (kps.includes(knowledgePoint)) return unit
  }
  return ''
}

// 某科目是否已建立知識點（用來判斷是否要求 AI 識別知識點）
export function hasKnowledgePoints(subject: string): boolean {
  return getKnowledgePoints(subject).length > 0
}

