// 產生給 Gemini 的章節對應提示（供 recognize prompt 使用）
// 會列出「大單元 → 知識點」，讓 AI 同時判斷 chapter 與 knowledge_point
export function buildTaxonomyPrompt(subject?: string): string {
  const entries = subject
    ? Object.entries(TAXONOMY).filter(([s]) => s === subject)
    : Object.entries(TAXONOMY)
  return entries
    .map(([sub, units]) => {
      const body = Object.entries(units)
        .map(([unit, kps]) =>
          kps.length > 0
            ? `  ◆ ${unit}：${kps.join('、')}`
            : `  ◆ ${unit}`,
        )
        .join('\n')
      return `【${sub}】\n${body}`
    })
    .join('\n\n')
}
